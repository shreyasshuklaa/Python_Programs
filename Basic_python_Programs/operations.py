a = 10
b = 5

# Arithmetic operations
print("Addition:", a + b)
print("Subtraction:", a - b)
print("Multiplication:", a * b)
print("Division:", a / b)   

# Comparison operations
print("a > b:", a > b)
print("a < b:", a < b)
print("a == b:", a == b)   
print("a != b:", a != b)   

# Logical operations
print((a > 5 and b < 10))   
print((a > 5 or b > 10))    
print(not(a > b))           